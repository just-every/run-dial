import { readFile, writeFile } from 'node:fs/promises';

// Unicode full default folding (C + F), not locale-specific lowercasing.
// The normative input and license are retained beside this generator.
const source = await readFile(new URL('./CaseFolding.txt', import.meta.url), 'utf8');
const mappings = {};
for (const line of source.split('\n')) {
  const match = /^([0-9A-F]+); [CF]; ([0-9A-F ]+);/.exec(line);
  if (match) mappings[parseInt(match[1], 16)] = String.fromCodePoint(...match[2].trim().split(' ').map(code => parseInt(code, 16)));
}
const root = new URL('../../', import.meta.url);
await writeFile(new URL('src/core/features/bookings/search/case-fold-data.json', root), JSON.stringify(mappings, null, 2) + '\n');
const literal = value => `'${value.replaceAll("'", "''")}'`;
const fold = value => `(WITH RECURSIVE fold(remaining, result) AS (
  SELECT ${value}, ''
  UNION ALL SELECT CAST(substr(CAST(remaining AS BLOB),
    max(1, length(CAST(substr(remaining, 1, 1) AS BLOB))) + 1) AS TEXT), result || coalesce(
    (SELECT folded FROM booking_search_casefold WHERE codepoint = unicode(remaining)),
    CASE WHEN unicode(remaining) IS NULL THEN char(0) ELSE substr(remaining, 1, 1) END)
  FROM fold WHERE length(CAST(remaining AS BLOB)) > 0
) SELECT result FROM fold WHERE length(CAST(remaining AS BLOB)) = 0)`;
const assign = prefix => `invitee_name_folded = ${fold(prefix + 'invitee_name')},
  invitee_email_folded = ${fold(prefix + 'invitee_email')}`;
const sql = `-- OPER-003: full default Unicode 17 case-fold search, including multi-codepoint mappings.
-- Generated by scripts/booking-search/generate.mjs from the retained Unicode CaseFolding.txt.
-- Source: https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt
-- License: scripts/booking-search/UNICODE-LICENSE.txt. Do not edit an applied migration.
CREATE TABLE booking_search_casefold (codepoint INTEGER PRIMARY KEY, folded TEXT NOT NULL);
INSERT INTO booking_search_casefold(codepoint, folded) VALUES
${Object.entries(mappings).map(([code, value]) => `(${code}, ${literal(value)})`).join(',\n')};

ALTER TABLE bookings ADD COLUMN invitee_name_folded TEXT NOT NULL DEFAULT '';
ALTER TABLE bookings ADD COLUMN invitee_email_folded TEXT NOT NULL DEFAULT '';

-- Normalize installed data in the migration itself, never during a timed list request.
UPDATE bookings SET ${assign('')};

-- Native triggers cover public/operator creation, saved move-in, and direct owner imports.
CREATE TRIGGER booking_search_insert AFTER INSERT ON bookings BEGIN
  UPDATE bookings SET ${assign('NEW.')} WHERE id = NEW.id;
END;
CREATE TRIGGER booking_search_invitee_update AFTER UPDATE OF invitee_name, invitee_email ON bookings BEGIN
  UPDATE bookings SET ${assign('NEW.')} WHERE id = NEW.id;
END;
CREATE INDEX booking_search_folded_idx ON bookings(invitee_name_folded, invitee_email_folded, id);
`;
await writeFile(new URL('migrations/core/0033_booking_search.sql', root), sql);
console.log(`Generated full Unicode folding data and migration: ${Object.keys(mappings).length} mappings.`);
