import { evidencePath } from "./evidence-path.mjs";
/* global document, innerWidth */
import assert from "node:assert/strict";
import { writeFile } from "node:fs/promises";
import { chromium } from "@playwright/test";
import { openGate } from "../tests/dev-key.mjs";

const origin = process.env.DIAL_REVIEW_ORIGIN ?? "http://127.0.0.1:15702";
const browser = await chromium.launch({ headless: true, args: ["--use-mock-keychain", "--password-store=basic"] });
const errors = [];
const inviteeName = `Browser invitee ${Date.now()}`;
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1024 }, timezoneId: "America/New_York" });
  const page = await context.newPage();
  page.setDefaultTimeout(20000);
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  page.on("response", async (response) => { if (response.url().includes("/api/") && response.status() >= 400) console.log(response.status(), new URL(response.url()).pathname, await response.text()); });
  await page.goto(origin + "/book/dial-host/intro");
  await page.locator(".pb-slot-button").first().waitFor();
  const weekLoaded = page.waitForResponse((response) => response.url().includes("/availability?") && response.ok());
  await page.getByRole("button", { name: "Next week", exact: true }).click();
  const week = await (await weekLoaded).json();
  const firstLabel = new Intl.DateTimeFormat("en-US", { timeZone: "Australia/Brisbane", dateStyle: "medium", timeStyle: "short" }).format(new Date(week.slots[0].startAt));
  await page.locator(".pb-slot-button").filter({ hasText: firstLabel }).first().waitFor();
  await page.screenshot({ path: evidencePath("booking-availability-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: evidencePath("booking-availability-mobile.png"), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "mobile availability has no horizontal overflow");
  await page.locator(".pb-slot-button").first().click();
  await page.waitForURL(/\/details\?/);
  await page.getByLabel("Name", { exact: true }).fill(inviteeName);
  await page.getByLabel("Email", { exact: true }).fill("browser@dial.test");
  await page.getByLabel("What would you like to discuss?", { exact: true }).fill("Synthetic browser booking");
  await page.getByRole("button", { name: "Confirm booking", exact: true }).click();
  try { await page.waitForURL(/\/confirmed\?/); } catch (error) { console.log(await page.locator("body").innerText()); console.log(errors); await page.screenshot({ path: evidencePath("browser-diagnostic.png"), fullPage: true }); throw error; }
  await page.getByRole("heading", { name: "You’re on the calendar.", exact: true }).waitFor();
  await page.screenshot({ path: evidencePath("booking-receipt-mobile.png"), fullPage: true });
  await page.request.post(origin + "/__fixtures/deliver", { data: {} });
  await page.request.post(origin + "/__fixtures/deliver", { data: {} });
  await page.getByRole("link", { name: "Manage booking", exact: true }).click();
  await page.getByRole("button", { name: "Cancel booking", exact: true }).waitFor();
  await page.getByLabel("Reason (optional)").fill("Synthetic browser cancellation");
  await page.getByRole("button", { name: "Cancel booking", exact: true }).click();
  await page.getByText("This booking has been cancelled.", { exact: true }).waitFor();
  await page.reload();
  await page.locator("main[aria-busy=false]").waitFor();
  assert.ok(await page.getByRole("button", { name: "Cancel booking", exact: true }).isDisabled(), "capability reload sees committed cancellation");
  await page.screenshot({ path: evidencePath("booking-cancelled-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1024 });
  await openGate(page.context(), origin);
  await page.goto(origin + "/signin");
  await page.getByLabel("Email address", { exact: true }).fill("operator@dial.test");
  await page.getByRole("button", { name: /Send magic link/ }).click();
  await page.getByRole("link", { name: "Open local outbox", exact: true }).click();
  await page.getByRole("link", { name: "Read message", exact: true }).first().click();
  await page.getByRole("link", { name: "Open this link", exact: true }).click();
  await page.getByRole("button", { name: "Confirm", exact: true }).click();
  await page.waitForURL(/\/app\/?$/);
  await page.getByRole("link", { name: "Bookings", exact: true }).click();
  await page.getByRole("button").filter({ hasText: inviteeName }).click();
  await page.getByRole("heading", { name: inviteeName, exact: true }).waitFor();
  await page.screenshot({ path: evidencePath("booking-operator-desktop.png"), fullPage: true });
  await page.request.post(origin + "/__fixtures/control", { data: { kind: "cancel", failure: true } });
  page.once("dialog", (dialog) => dialog.accept());
  if (await page.locator("details.dial-more").first().getAttribute("open") === null) await page.locator("details.dial-more > summary").first().click(); await page.getByRole("button", { name: "Erase invitee data", exact: true }).click();
  await page.getByRole("heading", { name: "Erasure cleanup", exact: true }).waitFor();
  await page.request.post(origin + "/__fixtures/deliver", { data: {} });
  await page.getByRole("button", { name: "Refresh cleanup status", exact: true }).click();
  await page.getByText("Calendar cleanup needs attention.", { exact: true }).waitFor();
  await page.request.post(origin + "/__fixtures/control", { data: { kind: "cancel", failure: false } });
  await page.getByRole("button", { name: "Retry cleanup", exact: true }).click();
  await page.getByText("Retry queued. Provider delivery will be checked again.", { exact: true }).waitFor();
  await page.request.post(origin + "/__fixtures/deliver", { data: {} });
  await page.reload();
  await page.getByText("Calendar cleanup completed.", { exact: true }).waitFor();
  assert.equal(await page.getByRole("heading", { name: inviteeName, exact: true }).count(), 0, "erased invitee is absent after reload");
  await page.screenshot({ path: evidencePath("booking-erasure-recovery-desktop.png"), fullPage: true });
  // Render the operator creation route as an initial document as well as by navigation.
  const create = await page.goto(origin + "/app/bookings/new");
  assert.equal(create.status(), 200);
  await page.getByRole("heading", { name: "Create booking", exact: true }).waitFor();
  assert.deepEqual(errors, []);
  await writeFile(evidencePath("booking-browser.json"), JSON.stringify({ verifiedAt: new Date().toISOString(), origin, errors, checks: ["real browser selection, details and confirmation", "mobile layout without horizontal overflow", "calendar receipt and manage capability", "cancel commit survives reload", "operator sign-in and booking workspace", "erasure cleanup failure and operator retry survive reload", "operator creation initial SSR document"] }, null, 2) + "\n");
  console.log("Booking browser journey passed.");
} finally { await browser.close(); }
