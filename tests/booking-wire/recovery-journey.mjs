import assert from "node:assert/strict";
import { assertLinkReady, wireMail } from "./mail-contracts.mjs";

export async function recoveryJourney({ data, call, state, book, deliver, future, checks }) {
  const control = (name, value) => data("/wire/control", { name, value });
  const bookingFor = async email => (await state()).bookings.find(row => row.invitee_email === email);
  const due = id => call("/__fixtures/due", { id }, 204);
  const deliverId = id => data("/__fixtures/deliver", { id });
  const calendarCommand = (snap, bookingId) => snap.delivery_outbox.find(row => row.booking_id === bookingId && row.kind === "calendar_upsert" && !row.idempotency_key.includes("conference-poll"));
  const retry = (bookingId, id) => data(`/api/app/bookings/${bookingId}/deliveries/${id}/retry`, {}, 202);
  const eventFor = (snap, id) => JSON.parse(snap.wire_events.find(row => row.id === id).payload);
  const eventsFor = (snap, bookingId) => snap.wire_events.map(row => JSON.parse(row.payload)).filter(row => row.extendedProperties.private["dial-booking-id"] === bookingId);

  await control("google-conference", "failure");
  const failed = await book(20); await deliver();
  let snap = await state(), booking = await bookingFor("wire20@dial.test");
  let command = calendarCommand(snap, booking.id);
  assert.equal(booking.state, "confirmed"); assert.equal(booking.calendar_state, "succeeded"); assert.equal(booking.meeting_state, "failed");
  assert.equal(command.state, "failed"); assert.equal(command.last_error_code, "meeting_creation_failed");
  assert.equal((await data(`/api/public/manage/${failed.token}`)).location.state, "pending");
  assertLinkReady(snap, "wire20@dial.test", 0);
  await control("google-conference", "success");
  const retried = await retry(booking.id, command.id);
  assert.equal((await retry(booking.id, command.id)).id, retried.id, "explicit retry is itself idempotent");
  await deliver();
  snap = await state(); booking = await bookingFor("wire20@dial.test");
  assert.equal(booking.meeting_state, "succeeded"); assert.equal(eventsFor(snap, booking.id).length, 1);
  const retryPatch = snap.wire_calls.find(row => row.method === "PATCH" && JSON.parse(row.body).conferenceData?.createRequest.requestId.includes(`retry:${command.id}`));
  assert.ok(retryPatch, "failed conference gets a new Google conference request on the same event");
  assertLinkReady(snap, "wire20@dial.test");
  checks.push("Google conference failure keeps booking; typed failure and idempotent operator retry yield one link-ready SendGrid email");

  await control("google-lost-response", 1);
  await book(24); await deliver();
  snap = await state(); booking = await bookingFor("wire24@dial.test"); command = calendarCommand(snap, booking.id);
  assert.equal(booking.state, "confirmed"); assert.equal(booking.calendar_state, "pending");
  assert.equal(command.state, "pending"); assert.equal(command.last_error_code, "provider_unavailable");
  assert.equal(eventsFor(snap, booking.id).length, 1, "provider committed even though Dial lost its response");
  const recoveredId = eventsFor(snap, booking.id)[0].id;
  const callsBefore = snap.wire_calls.length;
  await due(command.id); await deliver();
  snap = await state(); booking = await bookingFor("wire24@dial.test");
  assert.equal(booking.calendar_provider_event_id, recoveredId); assert.equal(booking.calendar_state, "succeeded");
  assert.equal(eventsFor(snap, booking.id).length, 1);
  const calls = snap.wire_calls.slice(callsBefore);
  assert.equal(calls.filter(row => row.method === "POST" && new URL(row.url).pathname.endsWith("/events")).length, 0);
  assert.ok(calls.some(row => row.method === "GET" && new URL(row.url).searchParams.get("privateExtendedProperty") === `dial-booking-id=${booking.id}`));
  const patch = calls.find(row => row.method === "PATCH" && new URL(row.url).pathname.endsWith(`/events/${recoveredId}`));
  assert.ok(patch); assert.ok(JSON.parse(patch.headers)["if-match"]);
  assert.equal(JSON.parse(patch.body).extendedProperties.private["dial-occurrence-id"], booking.current_occurrence_id);
  checks.push("lost Google response reconciles by persisted booking key and conditional PATCH without a duplicate event");

  await control("google-mutation-status", 503);
  const unavailable = await book(28); await deliver();
  booking = await bookingFor("wire28@dial.test"); command = calendarCommand(await state(), booking.id);
  for (let attempt = 0; attempt < 5; attempt++) { await due(command.id); await deliverId(command.id); }
  snap = await state(); command = snap.delivery_outbox.find(row => row.id === command.id);
  assert.equal(command.attempts, 6); assert.equal(command.state, "failed"); assert.equal(command.last_error_code, "provider_unavailable");
  booking = await bookingFor("wire28@dial.test");
  assert.equal(booking.state, "confirmed"); assert.equal(booking.calendar_state, "failed"); assert.equal(eventsFor(snap, booking.id).length, 0);
  assert.equal((await data(`/api/public/manage/${unavailable.token}`)).calendarState, "failed");
  assert.ok(!JSON.stringify(snap.delivery_attempts).includes("Private provider diagnostic"));
  assert.ok(!(await (await call(`/api/app/bookings/${booking.id}`)).text()).includes("Private provider diagnostic"));
  await control("google-mutation-status", 0); await retry(booking.id, command.id); await deliver();
  assert.equal((await bookingFor("wire28@dial.test")).calendar_state, "succeeded");
  checks.push("Google mutation 503 exhausts five bounded retries, preserves confirmed booking, sanitizes failure and supports explicit recovery");

  await control("google-conference", "pending");
  const stale = await book(32); await deliver();
  snap = await state(); booking = await bookingFor("wire32@dial.test");
  const oldOccurrence = booking.current_occurrence_id;
  const poll = snap.delivery_outbox.find(row => row.booking_id === booking.id && row.idempotency_key.includes("conference-poll"));
  assert.ok(poll); assert.equal(booking.meeting_state, "pending");
  const oldEvent = eventFor(snap, booking.calendar_provider_event_id);
  const available = await data(`/api/public/manage/${stale.token}/reschedule/availability?week=${future}`);
  const startAt = available.slots[36].startAt, inviteeTimezone = "UTC";
  const selection = await data(`/api/public/manage/${stale.token}/reschedule/selection`, { startAt, inviteeTimezone }, 201);
  await data(`/api/public/manage/${stale.token}/reschedule`, { nonce: selection.nonce, startAt, inviteeTimezone });
  await data("/wire/event", { id: oldEvent.id, payload: { ...oldEvent, conferenceData: { createRequest: { ...oldEvent.conferenceData.createRequest, status: { statusCode: "success" } }, entryPoints: [{ entryPointType: "video", uri: "https://meet.google.com/aaa-bbbb-ccc" }] } } });
  const staleCalls = (await state()).wire_calls.length;
  await due(poll.id); await deliverId(poll.id);
  snap = await state();
  assert.equal(snap.wire_calls.length, staleCalls, "superseded occurrence does not invoke Google or SendGrid");
  assert.equal(snap.delivery_outbox.filter(row => row.occurrence_id === oldOccurrence && row.idempotency_key.endsWith(":link-ready")).length, 0);
  await control("google-conference", "success"); await deliver();
  booking = await bookingFor("wire32@dial.test"); snap = await state();
  assert.notEqual(booking.current_occurrence_id, oldOccurrence);
  assert.equal(eventFor(snap, booking.calendar_provider_event_id).start.dateTime, startAt);
  assert.equal(eventFor(snap, booking.calendar_provider_event_id).extendedProperties.private["dial-occurrence-id"], booking.current_occurrence_id);
  assert.equal(wireMail(snap).filter(mail => mail.subject === "Your meeting link is ready" && mail.personalizations[0].to[0].email === "wire32@dial.test").length, 1);
  const canonical = eventFor(snap, booking.calendar_provider_event_id);
  await data("/wire/event", { id: canonical.id, payload: { ...oldEvent, updated: new Date(Date.now() + 1000).toISOString() } });
  await data("/wire/sync", {});
  snap = await state();
  assert.equal((await data(`/api/public/manage/${stale.token}`)).occurrence.startAt, startAt, "late Google occurrence cannot move the booking back");
  assert.equal(snap.booking_calendar_conflicts.filter(row => row.booking_id === booking.id).length, 0, "obsolete occurrence is repaired rather than treated as a current edit");
  assert.ok(snap.delivery_outbox.some(row => row.booking_id === booking.id && row.idempotency_key.includes("repair") && row.occurrence_id === booking.current_occurrence_id));
  await deliver();
  assert.equal(eventFor(await state(), canonical.id).start.dateTime, startAt);
  assertLinkReady(await state(), "wire32@dial.test");
  checks.push("late Meet completion for superseded occurrence has no provider effect; current occurrence alone owns link-ready mail");
}
