import assert from "node:assert/strict";
import { contract } from "./contract.mjs";
import { fixture, origin } from "./first-run/fixture.mjs";

contract("OPER-005", "native D1 setup gates documents and completes request-only through genuine auth and development mail", async t => {
  const { db, send, runtime, setCookie } = await fixture(t);
  const call = (path, body, headers) => send(path, { body, headers });
  assert.equal((await call("/setup")).status, 302);
  assert.equal((await call("/api/app/host-setup/complete", {})).status, 401);
  const boot = await call("/auth/bootstrap", { token: runtime.SETUP_TOKEN, displayName: "Owner", returnTo: "/setup" });
  assert.equal(boot.status, 303); setCookie(boot.headers.get("set-cookie").split(";")[0]);
  const ownerId = (await (await call("/api/app/session")).json()).operator.id;
  assert.equal((await db.prepare("SELECT onboarding_completed_at FROM operator_setup_identity").first()).onboarding_completed_at, null);
  for (const path of ["/app", "/app/bookings", "/app/settings?setup=1"]) assert.equal((await call(path)).headers.get("location"), "/setup");
  assert.equal((await call("/setup/profile")).status, 200);
  assert.equal((await call("/api/app/profile")).status, 200);
  for (const headers of [{ Origin: "https://foreign.example.test" }, { origin: "" }, { "sec-fetch-site": "cross-site" }]) assert.equal((await call("/api/app/host-setup/complete", {}, headers)).status, 403);
  assert.equal((await call("/api/app/host-setup/complete", {})).status, 409);
  assert.equal((await send("/api/app/profile", { method: "PATCH", body: { name: "Host", handle: "host", title: "Host", biography: "Scheduling", timezone: "UTC", focusAreas: [], socialProof: [] } })).status, 200);
  const defaults = await (await call("/api/app/__fixture/defaults")).json();
  const created = await call("/api/app/event-types", { ...defaults, title: "Requests", slug: "requests", description: "Propose a time", availability: [] });
  assert.equal(created.status, 201); const event = await created.json();
  assert.equal((await call(`/api/app/event-types/${event.id}/open-requests`, {})).status, 200, "actual development mail supports request-only without Google");
  assert.equal((await call("/api/app/host-setup/complete", {})).status, 409, "publication alone is not completion");
  assert.equal((await call(`/api/app/event-types/${event.id}/copy-report`, { url: origin + "/book/host/requests" })).status, 200);
  const response = await call("/api/app/host-setup/complete", {}); assert.equal(response.status, 200);
  const completed = await response.json(); assert.ok(completed.completedAt); assert.equal(completed.next, "/app");
  assert.equal((await call("/setup")).headers.get("location"), "/app");
  assert.equal((await call("/app/bookings")).status, 200);
  await db.prepare("UPDATE provider_connection_health SET status='unhealthy',last_checked_at='2000-01-01T00:00:00Z'").run();
  assert.equal((await send(`/api/app/event-types/${event.id}`, { method: "DELETE" })).status, 204);
  assert.deepEqual(await (await call("/api/app/host-setup/complete", {})).json(), completed, "finish does not recheck or rewrite after completion");
  assert.equal((await call("/setup/settings")).headers.get("location"), "/app");
  assert.equal((await call("/app")).status, 200);
  const invited = await call("/api/app/operators", { email: "second@example.test" });
  assert.equal(invited.status, 201);
  const secondId = (await invited.json()).operator.id;
  const confirm = async email => {
    const rows = (await db.prepare("SELECT message FROM rer_mail_development_outbox ORDER BY created_at DESC").all()).results;
    const message = rows.map(row => JSON.parse(row.message)).find(message => message.to.includes(email));
    const token = new URL(message.text.match(/https?:\/\/\S+/)[0]).searchParams.get("token");
    const response = await call("/auth/confirm", { token }); assert.equal(response.status, 303);
    return response.headers.get("set-cookie").split(";")[0];
  };
  const ownerCookie = boot.headers.get("set-cookie").split(";")[0];
  const secondCookie = await confirm("second@example.test");
  setCookie(ownerCookie);
  const selfRemoval = await call(`/api/app/operators/${ownerId}/remove`, {});
  assert.equal(selfRemoval.status, 409);
  assert.equal((await selfRemoval.json()).error.code, "self_erasure");
  setCookie(secondCookie);
  assert.equal((await (await call("/api/app/session")).json()).operator.id, secondId, "the ordinary operator consumed its native invitation");
  const protectedRemoval = await call(`/api/app/operators/${ownerId}/remove`, {});
  assert.equal(protectedRemoval.status, 409);
  assert.equal((await protectedRemoval.json()).error.code, "setup_operator_erasure_hold");
  setCookie(ownerCookie);
  assert.equal((await call(`/api/app/operators/${secondId}/remove`, {})).status, 204);
  assert.equal(await db.prepare("SELECT id FROM oa_operators WHERE id=?").bind(secondId).first(), null);
  setCookie(secondCookie);
  assert.equal((await call("/api/app/session")).status, 401);
  setCookie(ownerCookie);
  const reissued = await call("/api/app/operators", { email: "second@example.test" });
  assert.equal(reissued.status, 201);
  const replacementId = (await reissued.json()).operator.id;
  assert.notEqual(replacementId, secondId, "ordinary operator reinvitation creates a new native identity");
  setCookie(await confirm("second@example.test"));
  assert.equal((await (await call("/api/app/session")).json()).operator.id, replacementId, "the new identity consumed its genuine native invitation");
  assert.equal((await db.prepare("SELECT onboarding_completed_at FROM operator_setup_identity").first()).onboarding_completed_at, completed.completedAt, "ordinary operator removal and reinvitation preserve installation completion");
  assert.deepEqual(await (await call("/api/app/host-setup/complete", {})).json(), completed);
  assert.equal((await call("/setup")).headers.get("location"), "/app");
  assert.equal((await call("/app")).status, 200);
});
