import assert from "node:assert/strict";
import { button, field, get, mutation } from "./keyboard-controls.mjs";

export async function eventKeyboardJourney(page, origin, width, keys, checks, errors) {
  await keys.navigate("Event types");
  await keys.activate(page.getByRole("link", { name: "New event type", exact: true }), "Create event type");
  await button(page, "Save changes").waitFor();
  await keys.activate(button(page, "Save changes"), "Submit empty event");
  assert.ok(await field(page, "Event name").evaluate(el => el === globalThis.document.activeElement && el.validity.valueMissing && el.matches(":invalid")), "native required-field validation focuses the missing event name");
  await keys.type(field(page, "Event name"), `Keyboard event ${width}`, "Event name");
  await keys.type(field(page, "Description"), "A keyboard-created conversation", "Event description");
  await keys.type(field(page, "Private link, number, or address"), "https://meet.example.test/keyboard", "Private meeting link");
  const created = await mutation(page, "/api/app/event-types", () => keys.activate(button(page, "Save changes"), "Save new event"), 201);
  const event = await created.json();
  await button(page, "Save recurring availability").waitFor();
  // A new event starts on your hours; this one keeps its own, cleared, so its edits leave the other events' hours alone.
  await keys.select(field(page, "Schedule"), "", "Keep independent hours");
  await mutation(page, `/api/app/event-types/${event.id}/hours`, () => keys.activate(button(page, "Use independent hours"), "Use independent hours"));
  const starting = page.getByRole("button", { name: /^Remove \w+ window \d+$/ });
  for (let left = event.availability.length; left && await starting.count(); left--) await keys.activate(starting.first(), "Remove a starting window");
  const sunday = page.locator("div.rounded-2xl").filter({ has: page.getByRole("heading", { name: "Sunday", exact: true }) });
  await keys.activate(button(sunday, "Add window"), "Add Sunday availability");
  await keys.focus(field(page, "Sunday window 1 start time"), "Sunday start time");
  await page.keyboard.press("ArrowUp");
  const start = await field(page, "Sunday window 1 start time").inputValue();
  await mutation(page, `/api/app/event-types/${event.id}/availability`, () => keys.activate(button(page, "Save recurring availability"), "Save recurring availability"));
  await field(page, "Name").waitFor();
  const saved = await get(page, origin, `/api/app/event-types/${event.id}`);
  assert.equal(saved.availability.length, 1);
  const [hours, minutes] = start.split(":").map(Number);
  assert.equal(saved.availability[0].startMinute, hours * 60 + minutes);
  await mutation(page, `/api/app/event-types/${event.id}/details`, async () => {
    await keys.type(field(page, "Name"), `Keyboard edited ${width}`, "Edit saved event name");
    await page.keyboard.press("Tab");
  });
  await page.reload(); await field(page, "Name").waitFor();
  assert.equal(await field(page, "Name").inputValue(), `Keyboard edited ${width}`, "event edits persist after reload without a save button");
  assert.equal((await get(page, origin, `/api/app/event-types/${event.id}`)).title, `Keyboard edited ${width}`);
  await keys.activate(page.getByRole("link", { name: /^Advanced settings/ }), "Open event advanced settings");
  const sheet = page.getByRole("dialog", { name: "Advanced settings", exact: true });
  await sheet.waitFor({ state: "visible" });
  const sheetBounds = await sheet.boundingBox(), viewport = page.viewportSize();
  assert.equal(sheetBounds.x + sheetBounds.width, viewport.width, "advanced settings anchors to the right edge");
  assert.equal(sheetBounds.y, 0); assert.equal(sheetBounds.height, viewport.height);
  if (width === 390) assert.equal(sheetBounds.width, viewport.width, "phone settings use the full viewport");
  else assert.ok(sheetBounds.width < viewport.width, "desktop settings leave the event visible beside the sheet");
  const closeBounds = await button(page, "Close settings").boundingBox();
  assert.ok(closeBounds.y >= 0 && closeBounds.y + closeBounds.height <= viewport.height, "the close control stays in view");
  checks.push({ width, check: "Advanced sheet placement", sheetBounds, closeBounds, passed: true });
  await keys.activate(page.getByRole("button", { name: /^Questions/ }), "Open event questions");
  const question = field(page, "Question 1 label"), questionText = `Keyboard question ${width}`;
  await mutation(page, `/api/app/event-types/${event.id}/details`, async () => { await keys.type(question, questionText, "Edit question label"); await page.keyboard.press("Tab"); });
  await page.reload();
  await keys.activate(page.getByRole("button", { name: /^Questions/ }), "Reopen saved event questions");
  assert.equal(await question.inputValue(), questionText, "a question label persists after leaving its field and reloading");
  await keys.activate(page.getByRole("button", { name: /^Emails and calendar invite/ }), "Open invitation wording");
  assert.equal(await question.isVisible(), false, "opening another group folds the question group");
  const invitationTitle = page.getByRole("textbox", { name: /^Title/ });
  await mutation(page, `/api/app/event-types/${event.id}/correspondence`, async () => { await keys.type(invitationTitle, `Keyboard invitation ${width}`, "Edit invitation title"); await page.keyboard.press("Tab"); });
  await page.reload();
  await keys.activate(page.getByRole("button", { name: /^Emails and calendar invite/ }), "Reopen saved invitation wording");
  assert.equal(await invitationTitle.inputValue(), `Keyboard invitation ${width}`, "invitation wording persists without a save button");
  await keys.activate(button(page, "Close settings"), "Close event advanced settings");
  await page.waitForURL(origin + `/app/event-types/${event.id}`);
  const advancedRow = page.getByRole("link", { name: /^Advanced settings/ });
  await page.waitForFunction(element => element === globalThis.document.activeElement, await advancedRow.elementHandle());
  await keys.restored(advancedRow, "Advanced settings close");
  await keys.activate(advancedRow, "Reopen event advanced settings");
  await sheet.waitFor({ state: "visible" });
  await page.keyboard.press("Escape");
  await page.waitForURL(origin + `/app/event-types/${event.id}`);
  await page.waitForFunction(element => element === globalThis.document.activeElement, await advancedRow.elementHandle());
  await keys.restored(advancedRow, "Advanced settings Escape");
  await keys.activate(button(page, "Publish"), "Review publication requirements");
  await mutation(page, `/api/app/event-types/${event.id}/publish`, () => keys.activate(button(page, "Publish event"), "Publish event type"));
  assert.equal((await get(page, origin, `/api/app/event-types/${event.id}`)).status, "published");
  const eventCard = page.locator("section").filter({ has: page.getByRole("heading", { name: `Keyboard edited ${width}`, exact: true }) });
  async function openCardActions() {
    await keys.navigate("Event types");
    await eventCard.waitFor();
    const more = button(eventCard, "More actions");
    if (await more.isVisible()) {
      assert.equal(await more.getAttribute("aria-expanded"), "false");
      await keys.activate(more, "Reveal event actions");
      assert.equal(await more.getAttribute("aria-expanded"), "true");
    }
  }
  await openCardActions();
  await keys.focus(button(eventCard, "Copy booking link"), "Event card copy booking link");
  await keys.focus(button(eventCard, `Duplicate Keyboard edited ${width}`), "Event card duplicate");
  await keys.activate(eventCard.getByRole("link", { name: "Edit", exact: true }), "Event card edit");
  await field(page, "Name").waitFor();
  await openCardActions();
  await keys.activate(eventCard.getByRole("link", { name: "Availability", exact: true }), "Event card availability");
  await field(page, "Sunday window 1 start time").waitFor();
  await keys.navigate("Availability");
  const card = page.locator("section").filter({ has: page.getByRole("heading", { name: `Keyboard edited ${width}`, exact: true }) });
  await keys.activate(card.getByRole("link", { name: "Edit availability", exact: true }), "Open event from Availability");
  await field(page, "Sunday window 1 start time").waitFor();
  await keys.screenshot("availability");
  const addOverride = button(page, "Add date override");
  await keys.activate(addOverride, "Open date override editor");
  await keys.activate(button(page, "Cancel"), "Cancel date override");
  await keys.restored(addOverride, "Date override cancellation");
  assert.deepEqual(await get(page, origin, `/api/app/event-types/${event.id}/availability-overrides`), []);
  await keys.activate(addOverride, "Add date override");
  await keys.activate(button(page, "Save date override"), "Validate missing host date");
  const hostDate = field(page, "Host date");
  assert.ok(await hostDate.evaluate(el => el === globalThis.document.activeElement && el.validity.valueMissing));
  await keys.focus(hostDate, "Date override host date");
  for (let i = 0; i < 5; i++) await page.keyboard.press("ArrowLeft");
  for (const key of ["ArrowUp", "ArrowRight", "ArrowUp", "ArrowRight", "ArrowUp", "ArrowDown", "Tab"]) await page.keyboard.press(key);
  let date = await hostDate.inputValue(); assert.match(date, /^\d{4}-\d{2}-\d{2}$/);
  await keys.select(field(page, "Schedule for this date"), "open", "Date override mode");
  const overrideForm = hostDate.locator("xpath=ancestor::form");
  await keys.activate(button(overrideForm, "Add window"), "Add date-specific open window");
  const rejectedPath = `/api/app/event-types/${event.id}/availability-overrides/${date}`;
  await mutation(page, rejectedPath, () => keys.activate(button(page, "Save date override"), "Reject past date override"), 409);
  await page.getByRole("alert").filter({ hasText: "Past host dates cannot be changed." }).waitFor();
  const expectedError = errors.findIndex(error => error.location === origin + rejectedPath && /status of 409/.test(error.message));
  assert.ok(expectedError >= 0, "native past-date rejection accounts for the expected browser 409"); errors.splice(expectedError, 1);
  assert.deepEqual(await get(page, origin, `/api/app/event-types/${event.id}/availability-overrides`), []);
  await keys.screenshot("date-override-error");
  await keys.focus(hostDate, "Recover rejected host date");
  for (let i = 0; i < 5; i++) await page.keyboard.press("ArrowRight");
  await page.keyboard.press("ArrowUp"); await page.keyboard.press("ArrowUp"); await page.keyboard.press("Tab");
  date = await hostDate.inputValue();
  assert.ok(date > new Date().toISOString().slice(0, 10), "keyboard recovery chooses a future date");
  await mutation(page, `/api/app/event-types/${event.id}/availability-overrides/${date}`, () => keys.activate(button(page, "Save date override"), "Save recovered date override"));
  const overrides = await get(page, origin, `/api/app/event-types/${event.id}/availability-overrides`);
  assert.equal(overrides.length, 1); assert.equal(overrides[0].mode, "open"); assert.equal(overrides[0].windows.length, 1);
  await keys.restored(addOverride, "Date override save completion");
  await mutation(page, `/api/app/event-types/${event.id}/availability-overrides/${date}`, () => keys.activate(button(page, `Remove override for ${date}`), "Remove date override"), 204);
  assert.deepEqual(await get(page, origin, `/api/app/event-types/${event.id}/availability-overrides`), []);
  await keys.restored(addOverride, "Date override removal completion");
  await keys.activate(page.getByRole("link", { name: "Back to event", exact: true }), "Return to event");
  let dialogs = 0;
  const dialogProbe = async dialog => { dialogs++; await dialog.dismiss(); };
  page.on("dialog", dialogProbe);
  await keys.activate(button(page, "Event actions"), "Open lifecycle actions");
  await keys.activate(page.getByRole("menuitem", { name: "Pause", exact: true }), "Pause event");
  await mutation(page, `/api/app/event-types/${event.id}/disable`, () => keys.activate(button(page, "Pause event"), "Confirm pausing the event"));
  assert.equal((await get(page, origin, `/api/app/event-types/${event.id}`)).status, "disabled");
  await keys.activate(button(page, "Event actions"), "Open paused event actions");
  await keys.activate(page.getByRole("menuitem", { name: "Delete", exact: true }), "Review event deletion");
  const before = await get(page, origin, `/api/app/event-types/${event.id}`);
  await keys.activate(button(page, "Keep event"), "Cancel event deletion");
  assert.deepEqual(await get(page, origin, `/api/app/event-types/${event.id}`), before);
  await keys.screenshot("event-delete-cancelled");
  await keys.activate(button(page, "Event actions"), "Reopen event actions");
  await keys.activate(page.getByRole("menuitem", { name: "Delete", exact: true }), "Review event deletion again");
  await mutation(page, `/api/app/event-types/${event.id}`, () => keys.activate(button(page, "Delete event"), "Confirm event deletion"), 204);
  assert.equal(dialogs, 0, "event lifecycle changes use no browser-native dialog");
  page.off("dialog", dialogProbe);
  await page.getByRole("heading", { name: "Event types", exact: true, level: 1 }).waitFor();
  assert.ok(!(await get(page, origin, "/api/app/event-types")).some(row => row.id === event.id));
  checks.push({ width, flow: "Create, edit and delete event; event card and inline lifecycle actions through keyboard; native required validation; recurring availability keyboard edit and API readback", passed: true });
}
