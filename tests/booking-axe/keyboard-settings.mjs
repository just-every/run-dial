import assert from "node:assert/strict";
import { button, field, get, mutation } from "./keyboard-controls.mjs";

export async function settingsKeyboardJourney(page, origin, width, keys, checks, booking, errors) {
  await keys.navigate("Settings");
  await button(page, "Invite operator").waitFor();
  const destination = field(page, "Destination calendar");
  await keys.select(destination, "", "Calendar destination select");
  assert.equal(await destination.inputValue(), "");
  await keys.activate(button(page, "Save calendar selection"), "Validate missing calendar destination");
  await page.getByRole("alert").filter({ hasText: "Choose one writable destination" }).waitFor();
  await keys.select(destination, "synthetic-calendar", "Recover calendar destination");
  const conflict = page.getByRole("group", { name: "Conflict calendars", exact: true }).getByRole("checkbox");
  await keys.activate(conflict, "Remove conflict calendar selection", "Space");
  await keys.activate(button(page, "Save calendar selection"), "Validate empty conflict selection");
  await page.getByRole("alert").filter({ hasText: "Choose one writable destination" }).waitFor();
  await keys.activate(conflict, "Restore conflict calendar selection", "Space");
  await mutation(page, "/api/app/calendar/selection", () => keys.activate(button(page, "Save calendar selection"), "Save calendar selection"));
  const calendar = await get(page, origin, "/api/app/calendar/connection");
  assert.equal(calendar.destinationCalendarId, "synthetic-calendar"); assert.deepEqual(calendar.conflictCalendarIds, ["synthetic-calendar"]);
  await mutation(page, "/api/app/calendar/check", () => keys.activate(button(page, "Check connection"), "Check saved calendar connection"));
  assert.equal((await get(page, origin, "/api/app/calendar/connection")).state, "healthy");
  const preferences = await get(page, origin, "/api/app/mail/preferences");
  await keys.activate(field(page, "Mute booking mail for me"), "Toggle booking mail", "Space");
  await mutation(page, "/api/app/mail/preferences", () => keys.activate(button(page, "Save mail preference"), "Save mail preference"));
  assert.equal((await get(page, origin, "/api/app/mail/preferences")).bookingMailMuted, !preferences.bookingMailMuted);
  await page.getByRole("status").filter({ hasText: "Your booking mail preference is saved." }).waitFor();
  await keys.screenshot("settings-preference");
  const email = `keyboard-member-${width}@dial.test`;
  await keys.type(field(page, "Operator email"), email, "Operator email");
  await mutation(page, "/api/app/operators", () => keys.activate(button(page, "Invite operator"), "Invite operator"), 201);
  const members = await get(page, origin, "/api/app/operators");
  const member = members.operators.find(row => row.email === email); assert.ok(member);
  const protectedOwner = members.operators.find(row => row.setupOperator); assert.ok(protectedOwner);
  assert.ok(await button(page, `Remove ${protectedOwner.email}`).isDisabled(), "setup owner removal remains held");
  const remove = button(page, `Remove ${email}`);
  await keys.activate(remove, "Start member removal");
  await keys.activate(button(page, "Keep access"), "Cancel member removal");
  assert.deepEqual(await get(page, origin, "/api/app/operators"), members, "member cancellation does not change access");
  await keys.restored(remove, "Member removal cancellation");
  await keys.activate(remove, "Start member removal again");
  await mutation(page, `/api/app/operators/${member.id}/remove`, () => keys.activate(button(page, "Confirm removal"), "Confirm member removal"), 204);
  await page.getByRole("status").filter({ hasText: "Operator identity and local mail erased." }).waitFor();
  const remaining = await get(page, origin, "/api/app/operators");
  assert.ok(!remaining.operators.some(row => row.id === member.id));
  assert.ok(remaining.operators.some(row => row.id === protectedOwner.id));
  await keys.restored(button(page, "Invite operator"), "Member removal completion");
  await keys.screenshot("member-removed");

  const person = field(page, "Person’s email");
  await keys.type(person, "not-an-email", "Invalid erasure email");
  await mutation(page, "/api/app/privacy/preview", () => keys.activate(button(page, "Preview erasure"), "Request invalid erasure preview"), 400);
  const privacy = page.locator("section").filter({ has: page.getByRole("heading", { name: "Erase personal data", exact: true }) });
  await privacy.getByRole("alert").waitFor();
  const expectedError = errors.findIndex(error => error.location === origin + "/api/app/privacy/preview" && /status of 400/.test(error.message));
  assert.ok(expectedError >= 0, "the deliberate native validation response is the expected browser 400");
  errors.splice(expectedError, 1);
  const described = await person.getAttribute("aria-describedby");
  checks.push({ width, check: "server-rejected erasure email is invalid and described by its alert", passed: await person.getAttribute("aria-invalid") === "true" && Boolean(described) && await privacy.getByRole("alert").evaluate((el, id) => el.id === id, described) });
  await keys.screenshot("erasure-error");
  await keys.type(person, booking.inviteeEmail, "Erasure email");
  await mutation(page, "/api/app/privacy/preview", () => keys.activate(button(page, "Preview erasure"), "Preview personal data erasure"));
  await privacy.getByRole("status").filter({ hasText: "1 bookings" }).waitFor();
  const before = await get(page, origin, `/api/app/bookings/${booking.id}`);
  await keys.activate(button(privacy, "Cancel"), "Cancel personal data erasure");
  assert.deepEqual(await get(page, origin, `/api/app/bookings/${booking.id}`), before);
  await keys.restored(button(page, "Preview erasure"), "Personal erasure cancellation");
  await mutation(page, "/api/app/privacy/preview", () => keys.activate(button(page, "Preview erasure"), "Preview erasure again"));
  const erased = await mutation(page, "/api/app/privacy/erase", () => keys.activate(button(page, "Confirm permanent erasure"), "Confirm personal data erasure"));
  const receipt = await erased.json(); assert.equal(receipt.bookings, 1); assert.equal(receipt.localComplete, true);
  assert.equal((await get(page, origin, `/api/app/privacy/receipts/${receipt.id}`)).bookings, 1);
  assert.ok(!(await get(page, origin, `/api/app/bookings?query=${encodeURIComponent(booking.inviteeEmail)}`)).some(row => row.id === booking.id));
  const receiptElement = privacy.getByRole("status").filter({ hasText: "Erased 1 matching bookings" });
  await receiptElement.waitFor();
  assert.ok(await receiptElement.evaluate(el => el === globalThis.document.activeElement), "erasure completion focuses the announced receipt");
  await keys.screenshot("erasure-receipt");
  checks.push({ width, flow: "Settings preference, member invite/removal/cancellation and protected owner, person erasure validation/cancellation/receipt with native API readback", passed: true });
}
